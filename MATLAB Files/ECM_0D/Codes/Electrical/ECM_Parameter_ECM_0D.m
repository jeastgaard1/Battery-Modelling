        if battery_res.ECM.tau_RC2(tempValue,1)<0 ...
                || battery_res.ECM.tau_RC2(tempValue,1)==0 ...
                || isnan(battery_res.ECM.tau_RC2(tempValue,1))>0
            msg.error.ECM.tau_RC2=1;
            battery_res.ECM.tau_RC2(tempValue,1)=battery_res.ECM.tau_RC2(tempValue,1).*floor(battery_res.ECM.tau_RC2(tempValue,1)./abs(battery_res.ECM.tau_RC2(tempValue,1)*1.05)) ...
