                || battery_res.ECM.tau_RC3(tempValue,1)==0 ...
                || isnan(battery_res.ECM.tau_RC3(tempValue,1))>0
            msg.error.ECM.tau_RC3=1;
            battery_res.ECM.tau_RC3(tempValue,1)=battery_res.ECM.tau_RC3(tempValue,1).*floor(battery_res.ECM.tau_RC3(tempValue,1)./abs(battery_res.ECM.tau_RC3(tempValue,1)*1.05)) ...
                +floor(1-battery_res.ECM.tau_RC3(tempValue,1)./abs(battery_res.ECM.tau_RC3(tempValue,1)*1.05))*1e-3;
        end
    else
        %R0 #######################################################################
        battery_res.ECM.R(tempValue,1)=param.fit.CH.R0(battery_res.SoC(tempValue,1),battery_res.T(tempValue,1)) ...
            *battery_res.Aging.SoH_R(1,1)*options.Electrical.R_fac;
        if battery_res.ECM.R(tempValue,1)<0 ...
                || battery_res.ECM.R(tempValue,1)==0 ...
                || isnan(battery_res.ECM.R(tempValue,1))>0
            msg.error.ECM.R=1;
            battery_res.ECM.R(tempValue,1)=battery_res.ECM.R(tempValue,1).*floor(battery_res.ECM.R(tempValue,1)./abs(battery_res.ECM.R(tempValue,1)*1.05)) ...
                +floor(1-battery_res.ECM.R(tempValue,1)./abs(battery_res.ECM.R(tempValue,1)*1.05))*1e-3;
        end
        
        %RC1 ######################################################################
        battery_res.ECM.R_RC1(tempValue,1)=param.fit.CH.R_RC1(battery_res.SoC(tempValue,1),battery_res.T(tempValue,1)) ...
            *battery_res.Aging.SoH_R(1,1)*options.Electrical.RC1_fac;
        if battery_res.ECM.R_RC1(tempValue,1)<0 ...
                || battery_res.ECM.R_RC1(tempValue,1)==0 ...
                || isnan(battery_res.ECM.R_RC1(tempValue,1))>0
            msg.error.ECM.R_RC1=1;
            battery_res.ECM.R_RC1(tempValue,1)=battery_res.ECM.R_RC1(tempValue,1).*floor(battery_res.ECM.R_RC1(tempValue,1)./abs(battery_res.ECM.R_RC1(tempValue,1)*1.05)) ...
