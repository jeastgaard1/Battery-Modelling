            battery_res.ECM.R_RC3(tempValue,1)=battery_res.ECM.R_RC3(tempValue,1).*floor(battery_res.ECM.R_RC3(tempValue,1)./abs(battery_res.ECM.R_RC3(tempValue,1)*1.05)) ...
                +floor(1-battery_res.ECM.R_RC3(tempValue,1)./abs(battery_res.ECM.R_RC3(tempValue,1)*1.05))*1e-3;
        end
        battery_res.ECM.tau_RC3(tempValue,1)=param.fit.DCH.tau_RC3(battery_res.SoC(tempValue,1),battery_res.T(tempValue,1)) ...
